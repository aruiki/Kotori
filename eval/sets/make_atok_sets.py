def write(name, prefix, rows):
    assert len(rows) == 40, (name, len(rows))
    data = [{"index": f"{prefix}{i + 1:02d}", "context_text": "", "input": r, "expected_output": e}
            for i, (r, e) in enumerate(rows)]
    (HERE / name).write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


